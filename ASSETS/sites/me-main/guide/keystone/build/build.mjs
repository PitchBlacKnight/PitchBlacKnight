#!/usr/bin/env node
/**
 * Keystone token build.
 *
 *   tokens/*.tokens.json  (W3C DTCG)
 *        │
 *        ├─ resolve aliases, enforce one-way tier flow
 *        │
 *        ├─→ dist/keystone.css        CSS custom properties, light + dark
 *        ├─→ dist/keystone.tokens.json  flattened, resolved — for any other consumer
 *        ├─→ dist/Keystone.swift      iOS, proving the source is platform-agnostic
 *        └─→ dist/keystone.skill.md   machine-readable guidance, generated not written
 *
 * The last output is the point. The skill file falls out of the same source as the CSS,
 * so it cannot drift from the system it describes.
 *
 * Usage:  node build/build.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));

const primitive = read('tokens/primitive.tokens.json');
const semantic  = read('tokens/semantic.tokens.json');
const component = read('tokens/component.tokens.json');

const TIER = { primitive: 0, semantic: 1, component: 2 };
const errors = [];
const warnings = [];

/* ── flatten a DTCG tree into { 'dot.path': {$type,$value} } ──────────── */
function flatten(node, prefix = [], out = {}) {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (val && typeof val === 'object' && '$value' in val) {
      out[[...prefix, key].join('.')] = val;
    } else if (val && typeof val === 'object') {
      flatten(val, [...prefix, key], out);
    }
  }
  return out;
}

/* ── build the lookup table, one entry per mode for semantic ──────────── */
const flatPrimitive = flatten(primitive);
const flatSemanticAll = flatten(semantic);
const flatComponent = flatten(component);

const MODES = ['light', 'dark'];

// semantic paths arrive as `semantic.light.surface`; strip the mode so a
// component can reference `{semantic.surface}` and resolve per mode.
const semanticByMode = Object.fromEntries(MODES.map((m) => [m, {}]));
for (const [path, tok] of Object.entries(flatSemanticAll)) {
  const parts = path.split('.');            // semantic, <mode>, <name...>
  const mode = parts[1];
  if (!MODES.includes(mode)) continue;
  semanticByMode[mode]['semantic.' + parts.slice(2).join('.')] = tok;
}

const REF = /^\{([^}]+)\}$/;

function tierOf(path) {
  return TIER[path.split('.')[0]];
}

function resolve(path, token, mode, seen = new Set()) {
  const raw = token.$value;
  if (typeof raw !== 'string' || !REF.test(raw)) return raw;

  const target = raw.match(REF)[1];

  // ── governance: enforce one-way flow ──
  const from = tierOf(path);
  const to = tierOf(target);
  if (from !== undefined && to !== undefined && to > from) {
    errors.push(`${path} → {${target}} references a HIGHER tier. Flow must be primitive → semantic → component.`);
    return raw;
  }
  if (from !== undefined && to !== undefined && to === from) {
    warnings.push(`${path} → {${target}} is a same-tier reference. Usually a sign the token should not exist.`);
  }
  if (seen.has(target)) {
    errors.push(`Circular reference: ${[...seen, target].join(' → ')}`);
    return raw;
  }
  seen.add(path);

  const table = { ...flatPrimitive, ...semanticByMode[mode], ...flatComponent };
  const next = table[target];
  if (!next) {
    errors.push(`${path} → {${target}} does not resolve. Broken reference.`);
    return raw;
  }
  return resolve(target, next, mode, seen);
}

/* ── resolve everything, per mode ─────────────────────────────────────── */
const resolved = {};
for (const mode of MODES) {
  const table = { ...flatPrimitive, ...semanticByMode[mode], ...flatComponent };
  resolved[mode] = {};
  for (const [path, tok] of Object.entries(table)) {
    resolved[mode][path] = { $type: tok.$type, $value: resolve(path, tok, mode) };
  }
}

/* ── outputs ──────────────────────────────────────────────────────────── */
const cssVar = (p) => '--' + p.replace(/\./g, '-');
const cssValue = (t) =>
  Array.isArray(t.$value) ? t.$value.map((v) => (/\s/.test(v) ? `"${v}"` : v)).join(', ') : t.$value;

function emitCss() {
  const lines = [
    '/* Keystone — generated by build/build.mjs. Do not edit by hand. */',
    '/* Source: tokens/*.tokens.json (W3C DTCG)                        */',
    ''
  ];
  const isModal = (p) => p.startsWith('semantic.') || p.startsWith('component.');

  lines.push(':root {');
  for (const [p, t] of Object.entries(resolved.light)) {
    if (!isModal(p)) lines.push(`  ${cssVar(p)}: ${cssValue(t)};`);
  }
  lines.push('');
  lines.push('  /* light is the default mode */');
  for (const [p, t] of Object.entries(resolved.light)) {
    if (isModal(p)) lines.push(`  ${cssVar(p)}: ${cssValue(t)};`);
  }
  lines.push('}');
  lines.push('');
  lines.push('[data-theme="dark"] {');
  for (const [p, t] of Object.entries(resolved.dark)) {
    if (isModal(p) && cssValue(t) !== cssValue(resolved.light[p])) {
      lines.push(`  ${cssVar(p)}: ${cssValue(t)};`);
    }
  }
  lines.push('}');
  lines.push('');
  lines.push('@media (prefers-reduced-motion: reduce) {');
  lines.push('  *, *::before, *::after { animation-duration: .01ms !important; transition-duration: .01ms !important; }');
  lines.push('}');
  return lines.join('\n') + '\n';
}

function emitSwift() {
  const camel = (p) =>
    p.split('.').map((s, i) => (i === 0 ? s : s[0].toUpperCase() + s.slice(1))).join('').replace(/-(\w)/g, (_, c) => c.toUpperCase());
  const hexToSwift = (hex) => {
    const h = hex.replace('#', '');
    const [r, g, b] = [0, 2, 4].map((i) => (parseInt(h.slice(i, i + 2), 16) / 255).toFixed(3));
    return `Color(red: ${r}, green: ${g}, blue: ${b})`;
  };
  const out = ['// Keystone — generated. Same source as keystone.css.', 'import SwiftUI', '', 'enum KeystoneLight {'];
  for (const [p, t] of Object.entries(resolved.light)) {
    if (t.$type === 'color' && typeof t.$value === 'string' && t.$value.startsWith('#')) {
      out.push(`    static let ${camel(p)} = ${hexToSwift(t.$value)}`);
    }
  }
  out.push('}');
  return out.join('\n') + '\n';
}

function emitSkill() {
  const semanticNames = Object.keys(resolved.light).filter((p) => p.startsWith('semantic.'));
  const componentNames = Object.keys(resolved.light).filter((p) => p.startsWith('component.'));
  const spaceNames = Object.keys(resolved.light).filter((p) => p.startsWith('primitive.space.'));

  return `# Keystone — generated system guidance

<!-- GENERATED by build/build.mjs from tokens/*.tokens.json. Do not edit by hand.
     This file cannot drift from the system: it is built from the same source as the CSS. -->

## Counts

- primitive: ${Object.keys(resolved.light).filter((p) => p.startsWith('primitive.')).length}
- semantic:  ${semanticNames.length} (× ${MODES.length} modes)
- component: ${componentNames.length}

## Rules

1. Every value in generated code resolves to a token. A raw hex or an off-scale pixel is a defect.
2. Components bind to \`component.*\` or \`semantic.*\`. Never to \`primitive.*\` for colour.
3. Spacing comes only from this scale: ${spaceNames.map((p) => p.split('.').pop()).join(', ')}. Values between steps do not exist.
4. Every interactive element carries a visible \`:focus-visible\` ring using \`--semantic-focus-ring\`, 2px at 2px offset.
5. Minimum target 44×44, achieved with padding where the visual control is smaller.
6. No state is signalled by colour alone.

## Semantic tokens (the public API)

${semanticNames.map((p) => `- \`${cssVar(p)}\` — light \`${cssValue(resolved.light[p])}\` · dark \`${cssValue(resolved.dark[p])}\``).join('\n')}

## Component tokens

${componentNames.map((p) => `- \`${cssVar(p)}\``).join('\n')}
`;
}

/* ── write ────────────────────────────────────────────────────────────── */
mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, 'dist/keystone.css'), emitCss());
writeFileSync(join(ROOT, 'dist/Keystone.swift'), emitSwift());
writeFileSync(join(ROOT, 'dist/keystone.skill.md'), emitSkill());
writeFileSync(
  join(ROOT, 'dist/keystone.tokens.json'),
  JSON.stringify({ $description: 'Resolved Keystone tokens, all modes.', modes: resolved }, null, 2)
);

/* ── report ───────────────────────────────────────────────────────────── */
const count = Object.keys(resolved.light).length;
console.log(`\n  Keystone build`);
console.log(`  ${'─'.repeat(46)}`);
console.log(`  tokens resolved   ${count} × ${MODES.length} modes`);
console.log(`  outputs           dist/keystone.css`);
console.log(`                    dist/keystone.tokens.json`);
console.log(`                    dist/Keystone.swift`);
console.log(`                    dist/keystone.skill.md`);
if (warnings.length) {
  console.log(`\n  warnings (${warnings.length})`);
  warnings.forEach((w) => console.log(`    · ${w}`));
}
if (errors.length) {
  console.log(`\n  ERRORS (${errors.length})`);
  errors.forEach((e) => console.log(`    ✗ ${e}`));
  console.log('');
  process.exit(1);
}
console.log(`\n  governance        one-way flow enforced, 0 violations\n`);
